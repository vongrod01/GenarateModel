// Primary-key helper shared by every generator.
//
// The key columns come from the database itself (IsPrimaryKey / IsIdentity, returned by
// TableDescription in routers/connectDB_router.js) — never from column names such as ID or RxNo.

const flag = (v) => v === true || v === 1 || v === '1' || (typeof v === 'string' && v.toLowerCase() === 'true')

function describePk(dataSet) {
    const rows = Array.isArray(dataSet) ? dataSet : []
    const keys = rows.filter((f) => f && flag(f.IsPrimaryKey))
    const keyNames = new Set(keys.map((f) => f.FieldName))

    const isKey = (f) => keyNames.has(f.FieldName)
    // identity columns can never be inserted or updated, whether or not they are part of the key
    const isIdentity = (f) => flag(f.IsIdentity)
    // the identity column inside the key, if any (its value is generated by the database on insert)
    const identity = keys.find(isIdentity) || null

    return {
        keys,                                  // primary-key columns, in table order
        has: keys.length > 0,
        identity,                              // identity key column, or null
        isKey,
        isIdentity,
        // a key column the caller must supply on insert (every key except an identity column)
        isInsertKey: (f) => isKey(f) && !isIdentity(f),
        map: (fn) => keys.map(fn),
        join: (fn, sep = ', ') => keys.map(fn).join(sep),
        // position of a column inside the full column list (used for positional OUT params)
        indexOf: (f) => rows.findIndex((r) => r.FieldName === f.FieldName)
    }
}

// shown when a table has no primary key: get / edit / delete cannot be generated
function noPkNote(tbName) {
    return `${tbName} has no primary key, so get / edit / delete were not generated`
}

module.exports.describePk = describePk
module.exports.noPkNote = noPkNote
